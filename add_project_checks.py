def main():
    root = Path(__file__).resolve().parent
    if not (root / "backend" / "manage.py").is_file():
        raise SystemExit("Place add_project_checks.py in the project root first.")
    backup = root / "local_jobs" / "backups" / ("checks-" + datetime.now().strftime("%Y%m%d-%H%M%S-%f"))
    for relative, content in FILES.items():
        target = root / relative
        if target.is_file() and target.read_text(encoding="utf-8") != content:
            saved = backup / relative
            saved.parent.mkdir(parents=True, exist_ok=True)
            saved.write_bytes(target.read_bytes())
    for relative, content in FILES.items():
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        print("Ready:", relative)
    if backup.exists():
        print("Previous files backed up at:", backup)
    print("Next: python -m pip install -r requirements-dev.txt")
    print("Then: python -m pytest")


if __name__ == "__main__":
    main()
