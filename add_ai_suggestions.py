def main():
    root = Path(__file__).resolve().parent
    names = ["backend/index.html", "backend/MLFlowPro/urls.py", "backend/requirements.txt"]
    missing = [name for name in ["backend/manage.py", *names] if not (root / name).is_file()]
    if missing:
        raise SystemExit("Save this helper in the project root. Missing: " + ", ".join(missing))

    page = (root / names[0]).read_text(encoding="utf-8-sig")
    if "<!-- MLFlowPro: AI experiment suggestions -->" not in page:
        scripts = re.search(r"<script\b", page, re.IGNORECASE)
        if scripts is None:
            raise SystemExit("Could not find the dashboard scripts. No files changed.")
        page = page[:scripts.start()] + CARD + "\n" + page[scripts.start():]
    if "<!-- MLFlowPro: AI suggestion handler -->" not in page:
        closing_body = re.search(r"</body\s*>", page, re.IGNORECASE)
        if closing_body is None:
            raise SystemExit("Could not find the dashboard closing body tag. No files changed.")
        page = page[:closing_body.start()] + HANDLER + "\n" + page[closing_body.start():]

    urls = (root / names[1]).read_text(encoding="utf-8-sig")
    if not re.search(r"path\(\s*['\"]api/ai-suggestions/['\"]", urls):
        match = re.search(r"^urlpatterns\s*=\s*\[", urls, re.MULTILINE)
        if match is None:
            raise SystemExit("Could not find urlpatterns. No files changed.")
        import_line = "# MLFlowPro: AI experiment suggestions\nfrom experiments.ai_suggestions import suggest_experiment\n\n"
        urls = (urls[:match.start()] + import_line + urls[match.start():match.end()]
                + '\n    path("api/ai-suggestions/", suggest_experiment, name="ai-suggestions"),'
                + urls[match.end():])

    requirements = (root / names[2]).read_text(encoding="utf-8-sig")
    if re.search(r"^openai(?:\s|[<>=!~\[]|$)", requirements, re.IGNORECASE | re.MULTILINE):
        requirements = re.sub(r"^openai[^\n]*", "openai==2.54.0", requirements,
                              flags=re.IGNORECASE | re.MULTILINE)
    else:
        requirements = requirements.rstrip() + "\nopenai==2.54.0\n"

    contents = {**FILES, names[0]: page, names[1]: urls, names[2]: requirements}
    backup = root / "local_jobs" / "backups" / ("ai-" + datetime.now().strftime("%Y%m%d-%H%M%S-%f"))
    for relative, content in contents.items():
        target = root / relative
        if target.is_file() and target.read_text(encoding="utf-8") != content:
            saved = backup / relative
            saved.parent.mkdir(parents=True, exist_ok=True)
            saved.write_bytes(target.read_bytes())
    for relative, content in contents.items():
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        print("Ready:", relative)
    if backup.exists():
        print("Previous files backed up at:", backup)
    print("Next: install backend/requirements.txt and configure the three variables in docs/ai-suggestions.md.")


if __name__ == "__main__":
    main()
